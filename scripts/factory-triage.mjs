/** Mirrors `lib/findings.py:normalize_path`. */
export function normalizePath(path) {
  if (typeof path !== "string") return "";
  return path.replace(/\\/g, "/").trim().replace(/^[./]+/, "");
}

/** Mirrors `lib/findings.py:normalize_text`. */
export function normalizeText(text) {
  if (text === null || text === undefined) return "";
  const value = typeof text === "string" ? text : String(text);
  return value.trim().replace(/\s+/g, " ");
}

/** Mirrors `lib/findings.py:compute_fingerprint` — sha256(agent:rule_id:path:snippet). */
export function computeFingerprint({ agent, ruleId, path, snippet }) {
  const key = `${agent}:${ruleId}:${normalizePath(path)}:${normalizeText(snippet)}`;
  return createHash("sha256").update(key, "utf8").digest("hex");
}

// ---------------------------------------------------------------------------------------------
// Mirrored sanitisation (lib/redaction.py)
// ---------------------------------------------------------------------------------------------

/** Mirrors `lib/redaction.py:mask_text` — mask anything credential-shaped, same labels. */
export function maskText(value) {
  if (typeof value !== "string") return value;
  let masked = value;
  for (const [name, pattern] of CREDENTIAL_SHAPES) {
    masked = masked.replace(pattern, `[redacted:${name}]`);
  }
  return masked;
}

/**
 * Mirrors `lib/redaction.py:redact_finding`. A credential agent's snippet never ships in any
 * form — it becomes a location, so an unrecognised credential format cannot slip through either.
 * Every other string is masked. Home paths are elided so a private report's location does not
 * ride along into a public tracker.
 */
export function sanitizeFinding(finding, { privateRoot } = {}) {
  const credentialClass = CREDENTIAL_AGENTS.has(finding.agent);
  const snippet = credentialClass
    ? `[withheld: credential-class agent — see the private report at ${finding.path}:${finding.lineNumber ?? "?"}]`
    : maskText(finding.snippet ?? "");
  const elide = (value) => {
    if (typeof value !== "string") return value;
    let out = maskText(value);
    const home = homedir();
    if (home) out = out.split(home).join("~");
    if (privateRoot) out = out.split(privateRoot).join("<private-report-dir>");
    // Any remaining absolute home-shaped path (a different operator's tree) is elided too.
    out = out.replace(/\/(?:home|Users)\/[A-Za-z0-9._-]+/g, "~");
    return out;
  };
  return {
    title: elide(finding.title ?? ""),
    description: elide(finding.description ?? ""),
    remediation: elide(finding.remediation ?? ""),
    snippet,
    path: elide(finding.path),
    lineNumber: finding.lineNumber,
  };
}

// ---------------------------------------------------------------------------------------------
// Report parsing (the factory's own delta renderer: lib/findings.py:_render_delta_report)
// ---------------------------------------------------------------------------------------------

const FINDING_HEADING = /^### \[([^\]]+)\]\s+(.*?)\s+\(`([a-z]+)`\)\s*$/;
const FIELD = /^- \*\*(Rule|Location|Fingerprint|Description|Snippet|Remediation)\*\*:\s*(.*)$/;

/** Parse the badge. `[HIGH]`, `[HIGH · routed CRITICAL]`, `[FALSE POSITIVE]`. */
export function parseBadge(badge) {
  const text = badge.trim();
  if (/^FALSE POSITIVE$/i.test(text)) return { falsePositive: true };
  const routed = text.match(/^(\S+)\s*·\s*routed\s+(\S+)$/i);
  if (routed) {
    return { reported: routed[1].trim().toLowerCase(), routed: routed[2].trim().toLowerCase() };
  }
  return { reported: text.toLowerCase() };
}

/**
 * Parse a factory delta report into finding records.
 *
 * `agent` is the station name. The report's own filename is `<target>-<agent>-delta.md`, so the
 * caller derives it from the name; it cannot be read from the body, and identity is what decides
 * whether a finding may be published at all — hence the refusal below rather than a default.
 */
export function parseReport(markdown, { agent } = {}) {
  if (!agent) throw new Error("parseReport: `agent` is required (derive it from <target>-<agent>-delta.md)");
  const lines = String(markdown).split(/\r?\n/);
  const target = (lines.find((l) => l.startsWith("# Software Factory Delta Report:")) ?? "")
    .replace("# Software Factory Delta Report:", "")
    .trim();
  const findings = [];
  let inSection = false;
  let current = null;
  const flush = () => {
    if (current) findings.push(finishFinding(current, agent));
    current = null;
  };
  for (const line of lines) {
    if (line.startsWith("## ")) {
      flush();
      inSection = line.trim() === "## Action Required: New & Regressed Findings";
      continue;
    }
    if (!inSection) continue;
    const heading = line.match(FINDING_HEADING);
    if (heading) {
      flush();
      current = { badge: heading[1], heading: heading[2], state: heading[3], fields: {} };
      continue;
    }
    if (!current) continue;
    const field = line.match(FIELD);
    if (field) {
      current.fields[field[1]] = field[2].trim();
      continue;
    }
    // A wrapped continuation of the previous field (long descriptions are one line in the
    // renderer today, but CRLF/editor rewrites must not silently truncate a finding).
    if (/^\s+\S/.test(line) && Object.keys(current.fields).length > 0) {
      const last = Object.keys(current.fields).pop();
      current.fields[last] = `${current.fields[last]} ${line.trim()}`;
    }
  }
  flush();
  return { target, agent, findings };
}

function unquote(value) {
  const text = (value ?? "").trim();
  const ticked = text.match(/^`(.*)`$/);
  return ticked ? ticked[1] : text;
}

function finishFinding(raw, agent) {
  const badge = parseBadge(raw.badge);
  // The reduced (step-summary) form renders the rule id in the heading and omits the `Rule`
  // field entirely: `### [HIGH · routed critical] `path-traversal` (`new`)`. Reading only the
  // field left these as `unclassified`, which is exactly the identity a deferred finding must
  // still report correctly.
  const headingTicked = raw.heading.match(/^`(.*)`$/);
  const ruleId = unquote(raw.fields.Rule) || (headingTicked ? headingTicked[1] : "unclassified");
  const location = unquote(raw.fields.Location);
  const locationMatch = location.match(/^(.*):(\d+|\?)$/);
  const path = locationMatch ? locationMatch[1] : location;
  const lineNumber = locationMatch ? locationMatch[2] : "?";
  const fingerprintFromReport = unquote(raw.fields.Fingerprint).replace(/\.\.\.$/, "");
  const snippet = unquote(raw.fields.Snippet ?? "");
  const finding = {
    agent,
    ruleId,
    path,
    lineNumber,
    state: raw.state,
    title: headingTicked ? headingTicked[1] : raw.heading,
    description: raw.fields.Description ?? "",
    snippet,
    remediation: raw.fields.Remediation ?? "",
    falsePositive: Boolean(badge.falsePositive),
    severityReported: badge.reported ?? null,
    severityRouted: badge.routed ?? null,
    fingerprintFromReport: fingerprintFromReport || null,
  };
  finding.identityCritical = IDENTITY_CRITICAL_AGENTS.has(agent);
  finding.className = STATION_CLASSES[agent] ?? "quality";
  // Effective severity mirrors `lib/embargo.py:effective_severity`, fail-closed: an identity
  // rule cannot be argued away by the model's label, and a missing or unknown label is
  // `critical` — never `medium`, which is the band public sinks publish.
  const routed = finding.severityRouted ?? finding.severityReported;
  finding.effectiveSeverity = finding.identityCritical
    ? "critical"
    : VALID_SEVERITIES.includes(routed)
      ? routed
      : "critical";
  // Identity is recomputable only when the report carried the fields the factory hashes.
  const canRecompute = Boolean(path) && Boolean(raw.fields.Snippet !== undefined);
  finding.fingerprint = canRecompute
    ? computeFingerprint({ agent, ruleId, path, snippet })
    : null;
  finding.identitySource = finding.fingerprint
    ? finding.fingerprintFromReport && finding.fingerprint.startsWith(finding.fingerprintFromReport)
      ? "recomputed-and-verified"
      : "recomputed-mismatch"
    : "unverifiable";
  return finding;
}

// ---------------------------------------------------------------------------------------------
// Policy: severity mapping, routing, bead construction
// ---------------------------------------------------------------------------------------------

/** Priority mapping. `critical`/`high` never reach a public board except as a deferred record. */
export function priorityFor(finding) {
  switch (finding.effectiveSeverity) {
    case "critical":
      return 1;
    case "high":
      return 1;
    case "medium":
      return 2;
    default:
      return 3;
  }
}

/** The deterministic functionality-change hint. A hint only; `--functionality-change` confirms. */
export function suggestsFunctionalityChange(finding) {
  const text = `${finding.remediation} ${finding.description}`;
  return FUNCTIONALITY_CHANGE_SIGNALS.some((pattern) => pattern.test(text));
}

/**
 * Decide what happens to one finding. This is the whole policy, in one place, so the doc and the
 * tests can point at it rather than re-describe it.
 *
 * Returned `action`:
 *   - `file`   — a sanitised public bead is allowed.
 *   - `defer`  — sensitive and embargoed: private escalation only, NO public bead.
 *   - `skip`   — not actionable (false positive, unchanged, unmapped state).
 *   - `blocked`— sanitised bead, filed BLOCKED with `human-review`: the remediation changes
 *                behaviour and a human decides whether it is wanted (never an auto-fix).
 */
export function routeFinding(finding, { confirmedFunctionalityChange = false, includeLow = false } = {}) {
  const reasons = [];
  if (finding.falsePositive) return { action: "skip", reasons: ["triaged false positive by the factory"] };
  if (finding.state === "unchanged") return { action: "skip", reasons: ["unchanged: already tracked"] };
  if (!["new", "regressed"].includes(finding.state)) {
    return { action: "skip", reasons: [`state \`${finding.state}\` is not an action state`] };
  }
  if (finding.identitySource === "unverifiable") {
    return {
      action: "defer",
      reasons: ["identity unverifiable: the report carried no recomputable fingerprint (reduced/step-summary form)"],
    };
  }
  if (finding.identitySource === "recomputed-mismatch") {
    return {
      action: "defer",
      reasons: [
        "identity mismatch: the recomputed fingerprint does not match the report's prefix — refusing to file under an unverified identity",
      ],
    };
  }
  if (EMBARGOED_SEVERITIES.has(finding.effectiveSeverity)) {
    // One decision, not two: an identity-critical agent is already forced to `critical` above
    // (`effective_severity` behaviour), so a separate identity branch here would be unreachable
    // — the identity belongs in the reason a human reads, not in a second check that can never
    // fire. Mutation testing is what showed the difference.
    if (finding.effectiveSeverity === "critical") {
      return {
        action: "defer",
        reasons: [
          finding.identityCritical
            ? `sensitive critical: identity-critical agent \`${finding.agent}\` routes as critical whatever the station labelled it, and critical detail is never published to a public tracker`
            : "critical severity is deferred for a human regardless of station class (fail-closed)",
        ],
      };
    }
    reasons.push("high severity from a non-sensitive station: filed sanitised at P1");
  }
  if (["low", "info"].includes(finding.effectiveSeverity) && !includeLow) {
    return { action: "skip", reasons: [`${finding.effectiveSeverity} is below the board band (pass --include-low to file at P3)`] };
  }
  const functionality = confirmedFunctionalityChange || suggestsFunctionalityChange(finding);
  if (functionality) {
    return {
      action: "blocked",
      reasons: [
        confirmedFunctionalityChange
          ? "the analyst confirmed this remediation changes functionality"
          : "the remediation reads as a functionality change",
        "human decides whether the behaviour change is wanted: filed BLOCKED with `human-review`, never auto-fixed",
      ],
    };
  }
  return { action: "file", reasons: reasons.length ? reasons : ["publishable band"] };
}

/** Build the bead the factory's own `beads` sink would build, plus this policy's priority/labels. */
export function buildBead(finding, verdict, { privateRoot, target } = {}) {
  const published = sanitizeFinding(finding, { privateRoot });
  const type = /vuln|secret/.test(finding.agent) ? "bug" : "task";
  const labels = ["factory", `station:${finding.agent}`, `class:${finding.className}`];
  if (verdict.action === "blocked") labels.push("human-review");
  if (finding.state === "regressed") labels.push("regression");
  const decision = verdict.action === "blocked" ? "\n\nDecision needed: confirm whether to change this behaviour (yes/no) and, if yes, file the change as its own bead." : "";
  const body = [
    `Factory \`${finding.agent}\` (${finding.className}) reported this finding; the full report stays private and only this sanitised summary is published.`,
    "",
    `Rule: ${maskText(finding.ruleId)}`,
    `Path: ${published.path}:${published.lineNumber ?? "?"}`,
    `Severity: ${finding.effectiveSeverity}${finding.severityReported && finding.severityReported !== finding.effectiveSeverity ? ` (reported as ${finding.severityReported} by the station; treated as ${finding.effectiveSeverity})` : ""}`,
    `State: ${finding.state}`,
    "",
    published.description ? `Description: ${published.description}` : "",
    published.remediation ? `Remediation: ${published.remediation}` : "",
    published.snippet ? `Snippet:\n${published.snippet}` : "",
    decision,
    `Fingerprint: ${finding.fingerprint}`,
    `External reference: ${BEAD_EXTERNAL_REF_PREFIX}${finding.fingerprint}`,
  ]
    .filter((line) => line !== "")
    .join("\n");
  const title = maskText(`[${finding.agent}] ${finding.title}`).slice(0, 120);
  return {
    title,
    description: body,
    type,
    priority: priorityFor(finding),
    labels,
    externalRef: `${BEAD_EXTERNAL_REF_PREFIX}${finding.fingerprint}`,
    fingerprint: finding.fingerprint,
    target: target ?? null,
  };
}


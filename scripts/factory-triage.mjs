/** The private report root. Reports never live in the repository working tree. */
export function privateRootFromEnv(env = process.env) {
  if (env.VOICEBOX_FACTORY_PRIVATE_DIR) return resolve(env.VOICEBOX_FACTORY_PRIVATE_DIR);
  return join(homedir(), ".voicebox", "factory-reports");
}

/** True when `path` is inside `root` (symlinks resolved as far as the path exists). */
export function isInside(path, root) {
  const real = (value) => {
    try {
      return realpathSync(value);
    } catch {
      // The target may not exist yet (a report dir); resolve the closest existing ancestor.
      let parent = dirname(resolve(value));
      const seen = [];
      while (!existsSync(parent) && dirname(parent) !== parent) {
        seen.push(basename(parent));
        parent = dirname(parent);
      }
      const base = existsSync(parent) ? realpathSync(parent) : resolve(parent);
      return join(base, ...seen.reverse(), basename(resolve(value)));
    }
  };
  const contained = (candidate, base) =>
    candidate === base || candidate.startsWith(base.endsWith(sep) ? base : base + sep);
  // BOTH the named path and the resolved target are checked. A symlink that lives inside the
  // repository and points at a private report resolves outside, so a realpath-only check would
  // accept it — and one `git add -A` would then commit the link to the unredacted report
  // (review of 929c559, Finding 3).
  const lexicalPath = resolve(path);
  const lexicalRoot = resolve(root);
  if (contained(lexicalPath, lexicalRoot)) return true;
  return contained(real(path), real(root));
}

/**
 * Derive the station from `<target>-<agent>-delta.md`.
 *
 * The station is matched as a longest known suffix rather than split on the last hyphen: several
 * station names contain hyphens themselves (`docs-drift`, `vuln-discovery`, `deps-supply-chain`),
 * and a greedy `(.+)-([a-z0-9-]+)` split reads `voicebox-docs-drift-delta.md` as station `drift` —
 * an unknown station at best, and for a security station the wrong disclosure class. The station
 * list is the one `factory list` reports (`STATION_CLASSES`).
 */
export function agentFromReportName(file) {
  const base = basename(file).replace(/-delta\.md$/i, "");
  const matches = Object.keys(STATION_CLASSES).filter((station) => base === station || base.endsWith(`-${station}`));
  if (matches.length === 0) return null;
  return matches.sort((a, b) => b.length - a.length)[0];
}


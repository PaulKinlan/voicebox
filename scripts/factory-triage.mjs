/** Mirrors `lib/redaction.py:CREDENTIAL_AGENTS`. A scanner candidate *is* a credential. */
export const CREDENTIAL_AGENTS = new Set(["secret-scan"]);

/** Mirrors `lib/embargo.py:IDENTITY_CRITICAL_AGENTS` = CREDENTIAL_AGENTS | {vuln-*, threat-model}. */
export const IDENTITY_CRITICAL_AGENTS = new Set([
  ...CREDENTIAL_AGENTS,
  "vuln-discovery",
  "vuln-verify",
  "vuln-triage",
  "threat-model",
]);

/** Mirrors `lib/embargo.py:VALID_SEVERITIES`. Anything else is not a severity. */
export const VALID_SEVERITIES = Object.freeze(["critical", "high", "medium", "low", "info"]);

/** Mirrors `lib/embargo.py:EMBARGOED_SEVERITIES` — never published to a public tracker. */
export const EMBARGOED_SEVERITIES = new Set(["critical", "high"]);

/** Mirrors `lib/findings.py:BEAD_EXTERNAL_REF_PREFIX`. */
export const BEAD_EXTERNAL_REF_PREFIX = "factory:";


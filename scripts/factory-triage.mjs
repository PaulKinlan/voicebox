const FINDING_HEADING = /^### \[([^\]]+)\]\s+(.*?)\s+\(`([a-z]+)`\)\s*$/;
const FIELD = /^- \*\*(Rule|Location|Fingerprint|Description|Snippet|Remediation)\*\*:\s*(.*)$/;

/** Parse the badge. `[HIGH]`, `[HIGH · routed CRITICAL]`, `[FALSE POSITIVE]`. */
export function parseBadge(badge) {
  const text = badge.trim();
  if (/^FALSE POSITIVE$/i.test(text)) return { falsePositive: true };
  const routed = text.match(/^(\S+)\s*·\s*routed\s+(\S+)$/i);
  if (routed) {
    return { reported: routed[1].trim().toLowerCase(), routed: routed[2].trim().toLowerCase() };
  }
  return { reported: text.toLowerCase() };
}

/**
 * Parse a factory delta report into finding records.
 *
 * `agent` is the station name. The report's own filename is `<target>-<agent>-delta.md`, so the
 * caller derives it from the name; it cannot be read from the body, and identity is what decides
 * whether a finding may be published at all — hence the refusal below rather than a default.
 */
export function parseReport(markdown, { agent } = {}) {
  if (!agent) throw new Error("parseReport: `agent` is required (derive it from <target>-<agent>-delta.md)");
  const lines = String(markdown).split(/\r?\n/);
  const target = (lines.find((l) => l.startsWith("# Software Factory Delta Report:")) ?? "")
    .replace("# Software Factory Delta Report:", "")
    .trim();
  const findings = [];
  let inSection = false;
  let current = null;
  const flush = () => {
    if (current) findings.push(finishFinding(current, agent));
    current = null;
  };
  for (const line of lines) {
    if (line.startsWith("## ")) {
      flush();
      inSection = line.trim() === "## Action Required: New & Regressed Findings";
      continue;
    }
    if (!inSection) continue;
    const heading = line.match(FINDING_HEADING);
    if (heading) {
      flush();
      current = { badge: heading[1], heading: heading[2], state: heading[3], fields: {} };
      continue;
    }
    if (!current) continue;
    const field = line.match(FIELD);
    if (field) {
      current.fields[field[1]] = field[2].trim();
      continue;
    }
    // A wrapped continuation of the previous field (long descriptions are one line in the
    // renderer today, but CRLF/editor rewrites must not silently truncate a finding).
    if (/^\s+\S/.test(line) && Object.keys(current.fields).length > 0) {
      const last = Object.keys(current.fields).pop();
      current.fields[last] = `${current.fields[last]} ${line.trim()}`;
    }
  }
  flush();
  return { target, agent, findings };
}

function unquote(value) {
  const text = (value ?? "").trim();
  const ticked = text.match(/^`(.*)`$/);
  return ticked ? ticked[1] : text;
}

function finishFinding(raw, agent) {
  const badge = parseBadge(raw.badge);
  // The reduced (step-summary) form renders the rule id in the heading and omits the `Rule`
  // field entirely: `### [HIGH · routed critical] `path-traversal` (`new`)`. Reading only the
  // field left these as `unclassified`, which is exactly the identity a deferred finding must
  // still report correctly.
  const headingTicked = raw.heading.match(/^`(.*)`$/);
  const ruleId = unquote(raw.fields.Rule) || (headingTicked ? headingTicked[1] : "unclassified");
  const location = unquote(raw.fields.Location);
  const locationMatch = location.match(/^(.*):(\d+|\?)$/);
  const path = locationMatch ? locationMatch[1] : location;
  const lineNumber = locationMatch ? locationMatch[2] : "?";
  const fingerprintFromReport = unquote(raw.fields.Fingerprint).replace(/\.\.\.$/, "");
  const snippet = unquote(raw.fields.Snippet ?? "");
  const finding = {
    agent,
    ruleId,
    path,
    lineNumber,
    state: raw.state,
    title: headingTicked ? headingTicked[1] : raw.heading,
    description: raw.fields.Description ?? "",
    snippet,
    remediation: raw.fields.Remediation ?? "",
    falsePositive: Boolean(badge.falsePositive),
    severityReported: badge.reported ?? null,
    severityRouted: badge.routed ?? null,
    fingerprintFromReport: fingerprintFromReport || null,
  };
  finding.identityCritical = IDENTITY_CRITICAL_AGENTS.has(agent);
  finding.className = STATION_CLASSES[agent] ?? "quality";
  // Effective severity mirrors `lib/embargo.py:effective_severity`, fail-closed: an identity
  // rule cannot be argued away by the model's label, and a missing or unknown label is
  // `critical` — never `medium`, which is the band public sinks publish.
  const routed = finding.severityRouted ?? finding.severityReported;
  finding.effectiveSeverity = finding.identityCritical
    ? "critical"
    : VALID_SEVERITIES.includes(routed)
      ? routed
      : "critical";
  // Identity is recomputable only when the report carried the fields the factory hashes.
  const canRecompute = Boolean(path) && Boolean(raw.fields.Snippet !== undefined);
  finding.fingerprint = canRecompute
    ? computeFingerprint({ agent, ruleId, path, snippet })
    : null;
  finding.identitySource = finding.fingerprint
    ? finding.fingerprintFromReport && finding.fingerprint.startsWith(finding.fingerprintFromReport)
      ? "recomputed-and-verified"
      : "recomputed-mismatch"
    : "unverifiable";
  return finding;
}

